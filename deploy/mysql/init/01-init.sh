#!/bin/sh
set -eu

: "${MYSQL_ROOT_PASSWORD:?MYSQL_ROOT_PASSWORD is required}"
: "${MUSIC_DREAMER_IDENTITY_DB_USERNAME:?identity username is required}"
: "${MUSIC_DREAMER_IDENTITY_DB_PASSWORD:?identity password is required}"
: "${MUSIC_DREAMER_CATALOG_DB_USERNAME:?catalog username is required}"
: "${MUSIC_DREAMER_CATALOG_DB_PASSWORD:?catalog password is required}"
: "${MUSIC_DREAMER_INTERACTION_DB_USERNAME:?interaction username is required}"
: "${MUSIC_DREAMER_INTERACTION_DB_PASSWORD:?interaction password is required}"
: "${MUSIC_DREAMER_MEDIA_DB_USERNAME:?media username is required}"
: "${MUSIC_DREAMER_MEDIA_DB_PASSWORD:?media password is required}"

for value in \
  "$MUSIC_DREAMER_IDENTITY_DB_USERNAME" "$MUSIC_DREAMER_IDENTITY_DB_PASSWORD" \
  "$MUSIC_DREAMER_CATALOG_DB_USERNAME" "$MUSIC_DREAMER_CATALOG_DB_PASSWORD" \
  "$MUSIC_DREAMER_INTERACTION_DB_USERNAME" "$MUSIC_DREAMER_INTERACTION_DB_PASSWORD" \
  "$MUSIC_DREAMER_MEDIA_DB_USERNAME" "$MUSIC_DREAMER_MEDIA_DB_PASSWORD"; do
  case "$value" in
    *[!A-Za-z0-9._-]*)
      echo 'Database usernames and passwords may only contain A-Z, a-z, 0-9, dot, underscore, or hyphen.' >&2
      exit 1
      ;;
  esac
done

mysql --protocol=socket -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS music_dreamer_identity CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS music_dreamer_catalog CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS music_dreamer_interaction CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS music_dreamer_media CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS '$MUSIC_DREAMER_IDENTITY_DB_USERNAME'@'%' IDENTIFIED BY '$MUSIC_DREAMER_IDENTITY_DB_PASSWORD';
CREATE USER IF NOT EXISTS '$MUSIC_DREAMER_CATALOG_DB_USERNAME'@'%' IDENTIFIED BY '$MUSIC_DREAMER_CATALOG_DB_PASSWORD';
CREATE USER IF NOT EXISTS '$MUSIC_DREAMER_INTERACTION_DB_USERNAME'@'%' IDENTIFIED BY '$MUSIC_DREAMER_INTERACTION_DB_PASSWORD';
CREATE USER IF NOT EXISTS '$MUSIC_DREAMER_MEDIA_DB_USERNAME'@'%' IDENTIFIED BY '$MUSIC_DREAMER_MEDIA_DB_PASSWORD';

GRANT ALL PRIVILEGES ON music_dreamer_identity.* TO '$MUSIC_DREAMER_IDENTITY_DB_USERNAME'@'%';
GRANT ALL PRIVILEGES ON music_dreamer_catalog.* TO '$MUSIC_DREAMER_CATALOG_DB_USERNAME'@'%';
GRANT ALL PRIVILEGES ON music_dreamer_interaction.* TO '$MUSIC_DREAMER_INTERACTION_DB_USERNAME'@'%';
GRANT ALL PRIVILEGES ON music_dreamer_media.* TO '$MUSIC_DREAMER_MEDIA_DB_USERNAME'@'%';
FLUSH PRIVILEGES;
SQL
